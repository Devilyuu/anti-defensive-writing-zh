def split_sents(text):
    return [s for s in re.split(r"(?<=[。！？])", text) if s.strip()]


def scan(text, plain=False, only=None):
    """返回候选列表：[{line, cat, level, frag, hint}]。"""
    cats = list(CATS) + ([PLAIN_ONLY] if plain else [])
    lines = text.splitlines()
    results = []

    def add(no, cat, frag, level=None, hint=None):
        if only and cat not in only:
            return
        lv, ht = HINTS.get(cat, (level, hint))
        results.append({"line": no, "cat": cat, "level": level or lv, "frag": frag[:40], "hint": hint or ht})

    # 正文行（跳过代码块），记录段落
    body, in_code = [], False
    for no, line in enumerate(lines, 1):
        if line.strip().startswith("```"):
            in_code = not in_code
            continue
        body.append((no, "" if in_code else line))

    for no, line in body:
        if not line.strip():
            continue
        stripped = re.sub(r"`[^`\n]+`", lambda m: "§" * len(m.group(0)), line)  # 行内代码不查，用占位符保持位置
        spans = []
        for name, level, reg, hint in cats:
            target = line if name == "Markdown 残骸" else stripped
            for m in re.finditer(reg, target, flags=re.M):
                frag = m.group(0).strip()
                if not frag:
                    continue
                s, e = m.span()
                if any(s < pe and ps < e for ps, pe in spans):
                    continue
                spans.append((s, e))
                add(no, name, frag, level, hint)
        if REF.search(line):
            add(no, "参考文献（需核验）", line.strip())
        for s in split_sents(stripped):
            words = {w for w in HIGH_FREQ if w in s}
            if len(words) >= 4:
                add(no, "抽象词堆叠", "、".join(sorted(words, key=s.index)))
            marks = sum(bool(re.search(p, s)) for p in (r"通过", r"不(?:仅|只)", r"(?:还|更|也)(?:能够|可以|能)", r"从而|进而", r"为[^，。]{1,20}(?:提供|奠定|助力|保障)"))
            if marks >= 3:
                add(no, "目的链长句", s.strip())

    # 段落级：连续非空行为一段，标题行单独算
    paras, cur = [], []
    for no, line in body:
        if not line.strip() or HEADING.match(line) or re.match(r"^\s*#", line):
            if cur:
                paras.append(cur)
            cur = []
            continue
        cur.append((no, line))
    if cur:
        paras.append(cur)
    elevated = []
    for p in paras:
        text_p = "".join(l for _, l in p)
        sents = split_sents(text_p)
        conn = [s.strip()[:4] for s in sents if CONNECTIVE.match(re.sub(r"^[\s>*\-]+", "", s))]
        if len(conn) >= 3 and len(conn) * 2 >= len(sents):
            add(p[0][0], "连接词连用", "、".join(conn))
        if len(PAREN.findall(text_p)) >= 3:
            add(p[0][0], "括号过密", f"本段括号补充 {len(PAREN.findall(text_p))} 处")
        if len(sents) >= 2 and ELEVATE.search(sents[-1]):
            elevated.append((p[-1][0], sents[-1].strip()))
    if len(elevated) >= 2:
        for no, s in elevated:
            add(no, "段末升华", s)

    # 标题级
    heads = [(no, HEADING.match(l).group(1)) for no, l in body if l.strip() and HEADING.match(l)]
    first = next(((no, l.strip()) for no, l in body if l.strip()), None)
    duals = []
    for no, h in heads:
        m = re.fullmatch(r"([" + HAN + r"]{4,8})[，, ]([" + HAN + r"]{4,8})", h.strip())
        if m and abs(len(m.group(1)) - len(m.group(2))) <= 1:
            duals.append((no, h))
    if len(duals) >= 2:
        for no, h in duals:
            add(no, "小标题对仗", h)
    for no, h in ([first] if first else []) + heads:
        hit = [w for w in BIG_TITLE if w in h]
        if len(hit) >= 2:
            add(no, "标题大词", "、".join(hit))
    run = []
    for no, line in body + [(None, "")]:
        if line.strip() and re.match(r"^\s*(?:[-*+]\s*)?(?:\*\*)?[" + HAN + r"]{2,8}(?:\*\*)?[：:](?:\*\*)?\s*\S", line):
            run.append(no)
            continue
        if len(run) >= 3:
            add(run[0], "标签式冒号行", f"第{run[0]}–{run[-1]}行连续 {len(run)} 行")
        run = []
    # 引号混用（全文）
    plain_text = "\n".join(re.sub(r"`[^`\n]+`|\]\([^)\n]*\)", "", l) for _, l in body)
    styles = {"“”": len(re.findall(r"[“”]", plain_text)), "\"\"": plain_text.count('"'), "「」": len(re.findall(r"[「」]", plain_text))}
    used = {k: v for k, v in styles.items() if v}
    if len(used) >= 2:
        add(0, "引号混用", "，".join(f"{k}×{v}" for k, v in used.items()))
    # 相邻句同头：连续三句以同样两字开头
    sents = [(no, s) for no, line in body for s in split_sents(line)]
    for i in range(len(sents) - 2):
        hs = [re.sub(r"^[\s“「(（>*\-]+", "", s)[:2] for _, s in sents[i:i + 3]]
        if len(set(hs)) == 1 and re.fullmatch(r"[" + HAN + r"]{2}", hs[0]) and not re.match(r"^[一二三四五六七八九十]", hs[0]):
            add(sents[i][0], "相邻句同头", hs[0] + "…×3")
    return results


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    only = set(argv[argv.index("--only") + 1].split(",")) if "--only" in argv else None
    plain = "--plain" in argv or not argv[1].lower().endswith((".md", ".markdown"))
    results = scan(read(argv[1]), plain=plain, only=only)
    if "--json" in argv:
        print(json.dumps(results, ensure_ascii=False, indent=1))
        return 0
    if not results:
        print("没有命中候选。这不说明文字没问题，只说明没有命中本脚本的几类形态。")
        return 0
    by = {}
    for r in results:
        by.setdefault(r["cat"], []).append(r)
    order = [c[0] for c in CATS] + [PLAIN_ONLY[0]] + list(HINTS)
    print("候选位置（命中不是依据；强信号逐处看，弱信号成片才处理，排版错误见到就改）")
    for name in sorted(by, key=lambda n: (order.index(n) if n in order else 99)):
        items = by[name]
        print(f"\n[{name}]（{items[0]['level']}）×{len(items)}  提示：{items[0]['hint']}")
        if "--counts" in argv:
            continue
        for r in items:
            where = f"第{r['line']}行" if r["line"] else "全文"
            print(f"  {where}｜{r['frag']}")
    print("\n不作为依据：句内排比、正文设问、段长或句长是否整齐、比喻、被动句、名词化本身。人写的文章里这些同样常见。")
    return 0


